"""Embed app/src/remote/web/index.html into app/src/remote/remote_page.h (PROGMEM).

    python scripts/gen_remote_page.py          write the header
    python scripts/gen_remote_page.py --check  exit 1 if the header is out of date

The Arduino IDE cannot run build scripts, so the generated header is committed.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "app", "src", "remote", "web", "index.html")
DST = os.path.join(HERE, "..", "app", "src", "remote", "remote_page.h")
DELIM = "PAGE"


def render():
    with open(SRC, encoding="utf-8") as f:
        html = f.read().replace("\r\n", "\n")
    if ")" + DELIM + '"' in html:
        sys.exit("index.html contains the raw string delimiter")
    etag = hashlib.sha1(html.encode("utf-8")).hexdigest()[:12]
    return ("// Generated by scripts/gen_remote_page.py from web/index.html. Do not edit.\n"
            "#pragma once\n#include <pgmspace.h>\n\n"
            "namespace remote {\n"
            'static const char REMOTE_PAGE[] PROGMEM = R"' + DELIM + "(" + html + ")" + DELIM + '";\n'
            "// HTTP ETag: the phone keeps the page and only revalidates (304) until it changes\n"
            'static const char REMOTE_PAGE_ETAG[] = "\\"' + etag + '\\"";\n'
            "}  // namespace remote\n")


def main():
    text = render()
    if "--check" in sys.argv:
        try:
            with open(DST, encoding="utf-8") as f:
                ok = f.read() == text
        except FileNotFoundError:
            ok = False
        print("remote_page.h: " + ("up to date" if ok else "OUT OF DATE (run scripts/gen_remote_page.py)"))
        sys.exit(0 if ok else 1)
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.normpath(DST))


if __name__ == "__main__":
    main()
